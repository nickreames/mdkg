#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { validateManifest } = require("./release-ladder");

const repoRoot = path.resolve(__dirname, "..");
const manifestPath = path.join(repoRoot, "scripts", "smoke-manifest.json");
const packagePath = path.join(repoRoot, "package.json");
const workflowPath = path.join(repoRoot, ".github", "workflows", "release-readiness.yml");

function readTopology() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  const packageJson = JSON.parse(fs.readFileSync(packagePath, "utf8"));
  validateManifest(manifest, packageJson);
  return manifest.ci_topology;
}

function renderWorkflow(topology) {
  const fastMatrix = topology.fast.runtimes
    .flatMap((runtime) => [
      `          - id: ${runtime.id}`,
      `            node: "${runtime.version}"`,
    ])
    .join("\n");
  const shardMatrix = topology.full.shards
    .map((shard) => `          - shard: ${shard.id}`)
    .join("\n");
  const linuxFilesystemMatrix = topology.full.linux_filesystem.runners
    .flatMap((runner) => [
      `          - id: ${runner.id}`,
      `            runner: ${runner.label}`,
    ])
    .join("\n");
  return `# Generated by scripts/generate-ci-workflow.js from scripts/smoke-manifest.json.
# Run npm run ci:workflow:check; edit the manifest or generator, not this file.
name: Release readiness

on:
  push:
    branches: [main]
  pull_request:
  workflow_dispatch:
    inputs:
      tier:
        description: Verification tier
        type: choice
        required: true
        default: fast
        options:
          - fast
          - full
      commit_sha:
        description: Exact lowercase 40-character commit SHA required for the full tier
        type: string
        required: false
        default: ""

permissions:
  contents: read

concurrency:
  group: release-readiness-\${{ github.event_name == 'workflow_dispatch' && inputs.tier == 'full' && inputs.commit_sha || github.ref }}
  cancel-in-progress: \${{ github.event_name != 'workflow_dispatch' || inputs.tier != 'full' }}

jobs:
  fast:
    if: \${{ github.event_name != 'workflow_dispatch' || inputs.tier == 'fast' }}
    name: Fast / \${{ matrix.id }} / Node \${{ matrix.node }}
    runs-on: ubuntu-latest
    timeout-minutes: ${topology.fast.timeout_minutes}
    strategy:
      fail-fast: false
      matrix:
        include:
${fastMatrix}
    steps:
      - name: Prepare evidence directory
        run: |
          mkdir -p "$RUNNER_TEMP/mdkg-fast"
          printf '{"status":"started"}\\n' > "$RUNNER_TEMP/mdkg-fast/workflow-start.json"
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: \${{ matrix.node }}
          cache: npm
          cache-dependency-path: |
            package-lock.json
            docs/package-lock.json
            mdkg-dev/package-lock.json
      - name: Bootstrap all dependency owners
        run: npm run deps:bootstrap
      - name: Run manifest-backed fast release gate
        env:
          MDKG_RELEASE_RECEIPT_DIR: \${{ runner.temp }}/mdkg-fast
        run: npm run ci:release
      - name: Preserve interrupted fixture evidence and report failed cases
        if: \${{ always() }}
        run: node scripts/collect-ci-evidence.js "$RUNNER_TEMP/mdkg-fast" "$RUNNER_TEMP/mdkg-fast-fixtures"
      - name: Upload fast evidence
        if: \${{ always() }}
        uses: actions/upload-artifact@v4
        with:
          name: mdkg-fast-\${{ matrix.id }}-\${{ github.run_id }}
          path: |
            \${{ runner.temp }}/mdkg-fast
            !\${{ runner.temp }}/mdkg-fast/run-*/tmp/**
            \${{ runner.temp }}/mdkg-fast-fixtures
          retention-days: ${topology.fast.artifact_retention_days}
          if-no-files-found: error

  full_prepare:
    if: \${{ github.event_name == 'workflow_dispatch' && inputs.tier == 'full' }}
    name: Full / prepare exact SHA
    runs-on: ubuntu-latest
    timeout-minutes: ${topology.full.prepare_timeout_minutes}
    steps:
      - name: Prepare evidence directories
        run: |
          mkdir -p "$RUNNER_TEMP/mdkg-full-prepare" "$RUNNER_TEMP/mdkg-full-context"
          printf '{"status":"started"}\\n' > "$RUNNER_TEMP/mdkg-full-prepare/workflow-start.json"
      - name: Validate exact SHA input
        env:
          COMMIT_SHA: \${{ inputs.commit_sha }}
        run: '[[ "$COMMIT_SHA" =~ ^[a-f0-9]{40}$ ]]'
      - uses: actions/checkout@v4
        with:
          ref: \${{ inputs.commit_sha }}
          fetch-depth: 1
      - name: Verify detached exact SHA checkout
        env:
          COMMIT_SHA: \${{ inputs.commit_sha }}
        run: node scripts/generate-ci-workflow.js --verify-sha "$COMMIT_SHA"
      - uses: actions/setup-node@v4
        with:
          node-version: "${topology.full.runtime}"
          cache: npm
          cache-dependency-path: |
            package-lock.json
            docs/package-lock.json
            mdkg-dev/package-lock.json
      - name: Bootstrap all dependency owners
        run: npm run deps:bootstrap
      - name: Run shared full-release preparation
        env:
          MDKG_RELEASE_RECEIPT_DIR: \${{ runner.temp }}/mdkg-full-prepare
          MDKG_RELEASE_CONTEXT_DIR: \${{ runner.temp }}/mdkg-full-context
        run: npm run ci:full:prepare
      - name: Upload immutable full context
        uses: actions/upload-artifact@v4
        with:
          name: mdkg-full-context-\${{ inputs.commit_sha }}
          path: \${{ runner.temp }}/mdkg-full-context
          retention-days: ${topology.full.context_retention_days}
          if-no-files-found: error
      - name: Upload full preparation evidence
        if: \${{ always() }}
        uses: actions/upload-artifact@v4
        with:
          name: mdkg-full-prepare-\${{ inputs.commit_sha }}
          path: \${{ runner.temp }}/mdkg-full-prepare
          retention-days: ${topology.full.evidence_retention_days}
          if-no-files-found: error

  full_smoke:
    if: \${{ github.event_name == 'workflow_dispatch' && inputs.tier == 'full' }}
    needs: full_prepare
    name: Full / \${{ matrix.shard }}
    runs-on: ubuntu-latest
    timeout-minutes: ${topology.full.shard_timeout_minutes}
    strategy:
      fail-fast: false
      matrix:
        include:
${shardMatrix}
    steps:
      - name: Prepare evidence directories
        run: |
          mkdir -p "$RUNNER_TEMP/mdkg-full-\${{ matrix.shard }}" "$RUNNER_TEMP/mdkg-full-context"
          printf '{"status":"started"}\\n' > "$RUNNER_TEMP/mdkg-full-\${{ matrix.shard }}/workflow-start.json"
      - uses: actions/checkout@v4
        with:
          ref: \${{ inputs.commit_sha }}
          fetch-depth: 1
      - name: Verify detached exact SHA checkout
        env:
          COMMIT_SHA: \${{ inputs.commit_sha }}
        run: node scripts/generate-ci-workflow.js --verify-sha "$COMMIT_SHA"
      - uses: actions/setup-node@v4
        with:
          node-version: "${topology.full.runtime}"
          cache: npm
          cache-dependency-path: |
            package-lock.json
            docs/package-lock.json
            mdkg-dev/package-lock.json
      - name: Bootstrap all dependency owners
        run: npm run deps:bootstrap
      - name: Download immutable full context
        uses: actions/download-artifact@v4
        with:
          name: mdkg-full-context-\${{ inputs.commit_sha }}
          path: \${{ runner.temp }}/mdkg-full-context
      - name: Run exact manifest shard
        env:
          MDKG_RELEASE_RECEIPT_DIR: \${{ runner.temp }}/mdkg-full-\${{ matrix.shard }}
          MDKG_RELEASE_CONTEXT_DIR: \${{ runner.temp }}/mdkg-full-context
          MDKG_RELEASE_SHARD: \${{ matrix.shard }}
        run: npm run ci:full:shard
      - name: Upload shard evidence
        if: \${{ always() }}
        uses: actions/upload-artifact@v4
        with:
          name: mdkg-full-\${{ matrix.shard }}-\${{ inputs.commit_sha }}
          path: \${{ runner.temp }}/mdkg-full-\${{ matrix.shard }}
          retention-days: ${topology.full.evidence_retention_days}
          if-no-files-found: error

  # This deliberate stub keeps Test487 unqualified until exact-artifact
  # portable Node installed cases and independent platform evidence exist.
  # Bugs46/47 remain deferred/unresolved, not required native-helper fixes.
  # It runs only for an explicitly dispatched full tier, never for PR/push.
  full_linux_filesystem:
    if: \${{ github.event_name == 'workflow_dispatch' && inputs.tier == 'full' }}
    needs: full_prepare
    name: Full / Linux portable Node / \${{ matrix.id }} (unqualified)
    runs-on: \${{ matrix.runner }}
    timeout-minutes: ${topology.full.linux_filesystem.timeout_minutes}
    strategy:
      fail-fast: false
      matrix:
        include:
${linuxFilesystemMatrix}
    steps:
      - name: Refuse missing Test487 installed-artifact qualification
        run: |
          echo "::error title=Test487 unqualified::Portable Node installed cases are not yet qualified on Linux for the exact 0.6.0 artifact. Bugs46/47 remain deferred/unresolved; no platform acceptance is recorded."
          exit 1

  full_release:
    if: \${{ always() && github.event_name == 'workflow_dispatch' && inputs.tier == 'full' }}
    needs: [full_prepare, full_smoke, full_linux_filesystem]
    name: Full / aggregate release authority
    runs-on: ubuntu-latest
    timeout-minutes: ${topology.full.aggregate_timeout_minutes}
    steps:
      - name: Require preparation and every shard
        env:
          PREPARE_RESULT: \${{ needs.full_prepare.result }}
          SHARD_RESULT: \${{ needs.full_smoke.result }}
          LINUX_FILESYSTEM_RESULT: \${{ needs.full_linux_filesystem.result }}
        run: |
          test "$PREPARE_RESULT" = success
          test "$SHARD_RESULT" = success
          test "$LINUX_FILESYSTEM_RESULT" = success
`;
}

function validateWorkflowProjection(actual, expected = renderWorkflow(readTopology())) {
  if (actual === expected) {
    return { ok: true, bytes: Buffer.byteLength(actual) };
  }
  const actualLines = actual.split("\n");
  const expectedLines = expected.split("\n");
  const limit = Math.max(actualLines.length, expectedLines.length);
  for (let index = 0; index < limit; index += 1) {
    if (actualLines[index] !== expectedLines[index]) {
      throw new Error(
        `workflow projection mismatch at line ${index + 1}: expected ${JSON.stringify(expectedLines[index] ?? "<end-of-file>")}, got ${JSON.stringify(actualLines[index] ?? "<end-of-file>")}`,
      );
    }
  }
  throw new Error("workflow projection mismatch");
}

function validateShaInput(value) {
  const topology = readTopology();
  if (!(new RegExp(topology.full.exact_sha_pattern)).test(value || "")) {
    throw new Error("full release commit SHA must be exactly 40 lowercase hexadecimal characters");
  }
  return value;
}

function runGit(args, root = repoRoot) {
  const result = spawnSync("git", ["-C", root, ...args], { encoding: "utf8" });
  if (result.status !== 0) {
    throw new Error(`git ${args.join(" ")} failed: ${(result.stderr || result.stdout || "").trim()}`);
  }
  return result.stdout.trim();
}

function verifyExactSha(value, root = repoRoot) {
  const expected = validateShaInput(value);
  const actual = runGit(["rev-parse", "HEAD"], root);
  const symbolic = spawnSync("git", ["-C", root, "symbolic-ref", "-q", "HEAD"], { encoding: "utf8" });
  if (actual !== expected) {
    throw new Error(`checked out HEAD ${actual} does not match requested SHA ${expected}`);
  }
  if (symbolic.status === 0) {
    throw new Error(`full release checkout must be detached, found ${symbolic.stdout.trim()}`);
  }
  if (symbolic.status !== 1) {
    throw new Error(`unable to verify detached HEAD: ${(symbolic.stderr || "").trim()}`);
  }
  return { expected, actual, detached: true };
}

function main(argv = process.argv.slice(2)) {
  const topology = readTopology();
  const rendered = renderWorkflow(topology);
  if (argv[0] === "--write") {
    fs.mkdirSync(path.dirname(workflowPath), { recursive: true });
    fs.writeFileSync(workflowPath, rendered, "utf8");
    process.stdout.write(`wrote ${path.relative(repoRoot, workflowPath)}\n`);
    return 0;
  }
  if (argv[0] === "--check") {
    const actual = fs.existsSync(workflowPath) ? fs.readFileSync(workflowPath, "utf8") : "";
    validateWorkflowProjection(actual, rendered);
    process.stdout.write("release-readiness workflow matches deterministic source\n");
    return 0;
  }
  if (argv[0] === "--verify-sha-input") {
    process.stdout.write(`${JSON.stringify({ ok: true, commit_sha: validateShaInput(argv[1]) })}\n`);
    return 0;
  }
  if (argv[0] === "--verify-sha") {
    process.stdout.write(`${JSON.stringify({ ok: true, ...verifyExactSha(argv[1]) })}\n`);
    return 0;
  }
  process.stderr.write("Usage: node scripts/generate-ci-workflow.js <--write|--check|--verify-sha-input <sha>|--verify-sha <sha>>\n");
  return 2;
}

if (require.main === module) {
  try {
    process.exitCode = main();
  } catch (error) {
    process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  main,
  readTopology,
  renderWorkflow,
  validateShaInput,
  validateWorkflowProjection,
  verifyExactSha,
};
